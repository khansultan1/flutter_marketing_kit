  home:
    route: /
    title: Smart Dashboard
    subtitle: Track your expenses in real-time
  premium:
    route: /premium
    title: Premium Features
    subtitle: Unlock unlimited budgets & analytics
  settings:
    route: /settings
    title: Seamless Controls
    subtitle: Customize themes, currencies & privacy

